void* dlopen(const char *path, int mode) {
	if (path == NULL) { return &main_program_handle; }
	if (strcmp( path, "libpci.so.3" ) == 0) { dbg_print("(dlopen) found library libpci.so.3 (handle=%p)\n", &lib_libpci_so_3_libpci_so); return &lib_libpci_so_3_libpci_so; }
	if (strcmp( path, "libpci.so" ) == 0) { dbg_print("(dlopen) found library libpci.so (handle=%p)\n", &lib_libpci_so_3_libpci_so); return &lib_libpci_so_3_libpci_so; }
	
    if (strcmp( path, "libsoftokn3.so" ) == 0) { dbg_print("(dlopen) found library libsoftokn3.so (handle=%p)\n", &lib_libsoftokn3_so); return &lib_libsoftokn3_so; }
	if (strcmp( path, "libfreeblpriv3.so" ) == 0) { dbg_print("(dlopen) found library libfreeblpriv3.so (handle=%p)\n", &lib_libfreeblpriv3_so); return &lib_libfreeblpriv3_so; }
	if (strstr( path, "libnssckbi.so" ) != NULL) { dbg_print("(dlopen) found library libnssckbi.so (handle=%p)\n", &lib_libnssckbi_so); return &lib_libnssckbi_so; }
	
	if (strcmp( path, "libdrm.so" ) == 0) { dbg_print("(dlopen) found library libdrm.so (handle=%p)\n", &lib_libdrm_so); return &lib_libdrm_so; }
	if (strcmp( path, "libgbm.so" ) == 0) { dbg_print("(dlopen) found library libgbm.so (handle=%p)\n", &lib_libgbm_so); return &lib_libgbm_so; }

    if (strcmp( path, "libEGL.so.1" ) == 0) { dbg_print("(dlopen) found library libEGL.so.1 (handle=%p)\n", &lib_libEGL_so_1_libEGL_so); return &lib_libEGL_so_1_libEGL_so; }
	if (strcmp( path, "libEGL.so" ) == 0) { dbg_print("(dlopen) found library libEGL.so (handle=%p)\n", &lib_libEGL_so_1_libEGL_so); return &lib_libEGL_so_1_libEGL_so; }

	if (strcmp( path, "libGLESv2.so" ) == 0) { dbg_print("(dlopen) found library libGLESv2.so (handle=%p)\n", &lib_libGLESv2_so_2); return &lib_libGLESv2_so_2; }
	if (strcmp( path, "libGLESv2.so.2" ) == 0) { dbg_print("(dlopen) found library libGLESv2.so.2 (handle=%p)\n", &lib_libGLESv2_so_2); return &lib_libGLESv2_so_2; }

    fprintf(stderr, "(dlopen) WARNING: failed for path %s\n", path);	return stub_dlopen(path, mode);
}

