void* dlopen(const char *path, int mode) {
	if (path == NULL) { return &main_program_handle; }
	if (strcmp( path, "libgtk-4.so" ) == 0) { dbg_print("(dlopen) found library libgtk-4.so (handle=%p)\n", &lib_libgtk_4_so); return &lib_libgtk_4_so; }
	if (strcmp( path, "libEGL.so.1" ) == 0) { dbg_print("(dlopen) found library libEGL.so.1 (handle=%p)\n", &lib_libEGL_so_1); return &lib_libEGL_so_1; }
	if (strcmp( path, "libGLESv2.so.2" ) == 0) { dbg_print("(dlopen) found library libGLESv2.so.2 (handle=%p)\n", &lib_libGLESv2_so_2); return &lib_libGLESv2_so_2; }
	fprintf(stderr, "(dlopen) WARNING: failed for path %s\n", path);	return stub_dlopen(path, mode);
}

